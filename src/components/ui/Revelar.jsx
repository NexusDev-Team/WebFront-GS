import { motion } from 'framer-motion'

// Faz o bloco entrar uma vez ao aparecer na tela: fade e subida de 24 px (600 ms, curva suave).
// O <MotionConfig reducedMotion="user"> do App desliga o deslocamento para quem pede menos
// movimento. `atraso` (em segundos) escalona blocos vizinhos.
export default function Revelar({ atraso = 0, className = '', children }) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 24 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: '0px 0px -10% 0px' }}
      transition={{ duration: 0.6, delay: atraso, ease: [0.22, 1, 0.36, 1] }}
    >
      {children}
    </motion.div>
  )
}
